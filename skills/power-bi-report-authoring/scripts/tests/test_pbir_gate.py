"""pbir_gate.py must be read-only by default and write only with --apply."""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

_SCRIPTS = Path(__file__).resolve().parent.parent
GATE = _SCRIPTS / "pbir_gate.py"


def _make_report(root: Path) -> Path:
    """Minimal PBIR folder with one off-grid visual (finalize would snap it)."""
    rpt = root / "Demo.Report"
    page = rpt / "definition" / "pages" / "overview"
    visual = page / "visuals" / "card-kpi-revenue"
    visual.mkdir(parents=True)
    (rpt / "definition" / "report.json").write_text(json.dumps({"themeCollection": {}}), encoding="utf-8")
    (rpt / "definition" / "pages" / "pages.json").write_text(
        json.dumps({"pageOrder": ["overview"], "activePageName": "overview"}), encoding="utf-8")
    (page / "page.json").write_text(
        json.dumps({"name": "overview", "displayName": "Overview", "displayOption": "FitToPage",
                    "width": 1920, "height": 1080}), encoding="utf-8")
    (visual / "visual.json").write_text(
        json.dumps({"name": "card-kpi-revenue",
                    "position": {"x": 13, "y": 17, "width": 305, "height": 199, "z": 0},
                    "visual": {"visualType": "cardVisual"}}), encoding="utf-8")
    return rpt


def _digest(folder: Path) -> dict[str, str]:
    return {str(p.relative_to(folder)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(folder.rglob("*")) if p.is_file()}


def _run(rpt: Path, *extra: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(GATE), "--report", str(rpt), "--skip-validate", "--skip-schemas",
         "--allow-warnings", *extra],
        capture_output=True, text=True, timeout=120,
    )


def test_gate_is_read_only_by_default(tmp_path):
    rpt = _make_report(tmp_path)
    before = _digest(rpt)
    _run(rpt)
    assert _digest(rpt) == before, "default gate run must not modify or add files in the report"


def test_gate_apply_writes_changes(tmp_path):
    rpt = _make_report(tmp_path)
    before = _digest(rpt)
    result = _run(rpt, "--apply")
    assert _digest(rpt) != before, "--apply should let finalize snap/alt-text the visual"
    assert "backup written to" in result.stderr, "outside git, --apply must back the report up first"


def _git(cwd: Path, *args: str) -> None:
    subprocess.run(["git", *args], cwd=str(cwd), check=True, capture_output=True)


def _git_repo_with_report(root: Path) -> Path:
    rpt = _make_report(root)
    _git(root, "init", "-q")
    _git(root, "config", "user.email", "t@example.com")
    _git(root, "config", "user.name", "t")
    _git(root, "add", "-A")
    _git(root, "commit", "-q", "-m", "init")
    return rpt


def test_apply_in_clean_git_tree_is_allowed(tmp_path):
    rpt = _git_repo_with_report(tmp_path)
    before = _digest(rpt)
    result = _run(rpt, "--apply")
    assert "work tree clean" in result.stderr
    assert _digest(rpt) != before


def test_apply_refused_when_git_tree_dirty(tmp_path):
    rpt = _git_repo_with_report(tmp_path)
    (rpt / "definition" / "pages" / "overview" / "page.json").write_text("{}", encoding="utf-8")  # uncommitted edit
    before = _digest(rpt)
    result = _run(rpt, "--apply")
    assert result.returncode == 1 and "uncommitted" in (result.stderr + result.stdout)
    assert _digest(rpt) == before, "a refused --apply must not touch the report"
    forced = _run(rpt, "--apply", "--force-apply")
    assert forced.returncode != 1 or "uncommitted" not in forced.stderr


def test_gate_evidence_dir_override(tmp_path):
    rpt = _make_report(tmp_path)
    evidence = tmp_path / "evidence"
    _run(rpt, "--evidence-dir", str(evidence))
    assert (evidence / "design_report.md").exists()


# ── real fixture: a CLI-valid report generated by build_report_from_layout.py ─────────────────
import shutil  # noqa: E402

FIXTURE = Path(__file__).resolve().parent / "fixtures"
needs_cli = __import__("pytest").mark.skipif(not shutil.which("powerbi-report-author"),
                                             reason="powerbi-report-author not installed")


def _copy_fixture(tmp: Path) -> Path:
    shutil.copytree(FIXTURE, tmp / "proj")
    return tmp / "proj" / "Sample.Report"


def _full_gate(rpt: Path, *extra: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(GATE), "--report", str(rpt), "--allow-warnings", *extra],
        capture_output=True, text=True, timeout=180,
    )


@needs_cli
def test_fixture_passes_full_gate_including_schema_and_drift(tmp_path):
    rpt = _copy_fixture(tmp_path)
    before = _digest(rpt)
    result = _full_gate(rpt)
    assert result.returncode == 0, result.stderr
    assert "[ok  ] cli_validate" in result.stderr and "[ok  ] layout_drift" in result.stderr
    assert _digest(rpt) == before, "the gate must not modify the fixture"


@needs_cli
def test_gate_fails_on_layout_drift(tmp_path):
    rpt = _copy_fixture(tmp_path)
    vj = rpt / "definition" / "pages" / "overview" / "visuals" / "card-kpi-1" / "visual.json"
    data = json.loads(vj.read_text(encoding="utf-8"))
    data["position"]["x"] += 96
    vj.write_text(json.dumps(data), encoding="utf-8")
    result = _full_gate(rpt)
    assert result.returncode == 2 and "[FAIL] layout_drift" in result.stderr
    assert _full_gate(rpt, "--skip-drift").returncode == 0
